import { Schema, model, type Types } from 'mongoose';
import type { BaseDoc } from './types';

/**
 * A support ticket a store raises with the platform operator.
 *
 * WORKSPACE-LEVEL, and deliberately NOT branch-scoped: the person who hits a
 * problem is asking about the product, not about one till. `storeId` is kept as
 * a snapshot of where they were when they wrote it, because "it happens on the
 * Gulshan terminal" is the first thing the operator wants to know - it is
 * context, never a scope.
 *
 * The two kinds a store can raise are the two things anyone actually writes in:
 * something is broken, or something is missing. Anything else would be a
 * category nobody fills in honestly.
 *
 * The conversation is one reply from the platform side rather than a thread.
 * That is the whole shape of the first version: a store asks, the operator
 * answers and sets the status. A `replies` array would be the natural
 * extension, and nothing here forecloses it.
 */
export const SUPPORT_TICKET_TYPES = ['problem', 'feature'] as const;
export type SupportTicketType = (typeof SUPPORT_TICKET_TYPES)[number];

export const SUPPORT_TICKET_STATUSES = ['open', 'in_progress', 'resolved', 'closed'] as const;
export type SupportTicketStatus = (typeof SUPPORT_TICKET_STATUSES)[number];

/** Which part of the product the ticket is about. Free-form would not be filterable. */
export const SUPPORT_TICKET_AREAS = [
  'pos',
  'catalogue',
  'inventory',
  'customers',
  'reports',
  'printing',
  'billing',
  'staff',
  'other',
] as const;
export type SupportTicketArea = (typeof SUPPORT_TICKET_AREAS)[number];

export interface SupportTicketDoc extends BaseDoc {
  tenantId: Types.ObjectId;
  /** Where the reporter was signed in. Context for the operator, not a scope. */
  storeId: Types.ObjectId | null;
  /** `TKT-000012`, unique per workspace, generated by the server. */
  reference: string;
  type: SupportTicketType;
  status: SupportTicketStatus;
  area: SupportTicketArea;
  subject: string;
  /** Plain text. Never rendered as HTML, and stored with markup stripped. */
  message: string;
  /** The POS type of the workspace when the ticket was raised. */
  vertical: string;
  createdBy: Types.ObjectId | null;
  /** Who wrote it, as it read then - the account may be renamed or removed later. */
  createdByName: string;
  createdByEmail: string;
  /** The platform operator's answer. Plain text, same rule as the message. */
  reply: string;
  repliedAt: Date | null;
  repliedBy: Types.ObjectId | null;
  repliedByName: string;
}

const supportTicketSchema = new Schema<SupportTicketDoc>(
  {
    tenantId: { type: Schema.Types.ObjectId, ref: 'Tenant', required: true, index: true },
    storeId: { type: Schema.Types.ObjectId, ref: 'Store', default: null },
    reference: { type: String, required: true, trim: true, uppercase: true, maxlength: 32 },
    type: { type: String, enum: SUPPORT_TICKET_TYPES, required: true },
    status: { type: String, enum: SUPPORT_TICKET_STATUSES, default: 'open' },
    area: { type: String, enum: SUPPORT_TICKET_AREAS, default: 'other' },
    subject: { type: String, required: true, trim: true, maxlength: 140 },
    message: { type: String, required: true, trim: true, maxlength: 4000 },
    vertical: { type: String, default: '', trim: true, maxlength: 40 },
    createdBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
    createdByName: { type: String, default: '', trim: true, maxlength: 120 },
    createdByEmail: { type: String, default: '', trim: true, lowercase: true, maxlength: 254 },
    reply: { type: String, default: '', trim: true, maxlength: 4000 },
    repliedAt: { type: Date, default: null },
    repliedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
    repliedByName: { type: String, default: '', trim: true, maxlength: 120 },
  },
  { timestamps: true },
);

// One reference per workspace.
supportTicketSchema.index({ tenantId: 1, reference: 1 }, { unique: true });
// The store's own list: newest first, optionally narrowed by status or kind.
supportTicketSchema.index({ tenantId: 1, createdAt: -1 });
supportTicketSchema.index({ tenantId: 1, status: 1, createdAt: -1 });
// The platform inbox: every workspace at once, newest first, filtered the same way.
supportTicketSchema.index({ status: 1, createdAt: -1 });
supportTicketSchema.index({ type: 1, createdAt: -1 });
supportTicketSchema.index({ createdAt: -1 });

export const SupportTicketModel = model<SupportTicketDoc>('SupportTicket', supportTicketSchema);
