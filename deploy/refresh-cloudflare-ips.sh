#!/usr/bin/env bash
#
# Regenerate the Cloudflare real-IP list used by nginx, and the matching
# firewall allowlist.
#
# Why this is a script and not a list someone pasted once: Cloudflare adds
# ranges. A stale list has two failure modes, and both are bad. nginx stops
# trusting a new Cloudflare edge address, so every visitor routed through it
# gets logged and rate-limited as that edge rather than as themselves - one
# shared bucket for thousands of people. And a firewall built from the same
# stale list simply drops them.
#
# Run it from a checkout, commit the result, and deploy. It is deliberately
# NOT run during the image build: a build that reaches the network produces a
# different image every time and fails when the network does.
#
#   ./deploy/refresh-cloudflare-ips.sh            # write the files
#   ./deploy/refresh-cloudflare-ips.sh --check     # exit 1 if stale (for CI)
#
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

V4_URL="https://www.cloudflare.com/ips-v4"
V6_URL="https://www.cloudflare.com/ips-v6"
NGINX_OUT="docker/nginx/cloudflare-realip.conf"
UFW_OUT="deploy/cloudflare-ufw.generated.sh"

mode="write"
[ "${1:-}" = "--check" ] && mode="check"

fetch() {
  curl -fsS --max-time 20 --retry 2 --retry-delay 2 "$1"
}

# A range Cloudflare publishes, not one we invent: strict CIDR only. If their
# page is ever replaced by an error page or a captive portal, this rejects it
# rather than writing junk into a file that decides who nginx trusts.
valid_cidr() {
  printf '%s\n' "$1" | grep -Eq '^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$|^[0-9a-fA-F:]+/[0-9]{1,3}$'
}

echo "Fetching Cloudflare ranges..."
v4="$(fetch "$V4_URL")" || { echo "ERROR: could not fetch $V4_URL" >&2; exit 1; }
v6="$(fetch "$V6_URL")" || { echo "ERROR: could not fetch $V6_URL" >&2; exit 1; }

ranges=""
count=0
while IFS= read -r line; do
  line="$(printf '%s' "$line" | tr -d '\r' | tr -d '[:space:]')"
  [ -z "$line" ] && continue
  if ! valid_cidr "$line"; then
    echo "ERROR: refusing to write a non-CIDR value: '$line'" >&2
    exit 1
  fi
  ranges="${ranges}${line}"$'\n'
  count=$((count + 1))
done <<< "$v4"$'\n'"$v6"

# A plausible floor. Cloudflare publishes ~22 ranges; a handful would mean we
# fetched a truncated or wrong document, and shipping that would quietly shrink
# the trusted set.
if [ "$count" -lt 15 ]; then
  echo "ERROR: only $count ranges parsed, expected at least 15 - not writing" >&2
  exit 1
fi

stamp_note="# Generated by deploy/refresh-cloudflare-ips.sh from"

nginx_body="$stamp_note
#   $V4_URL
#   $V6_URL
# $count ranges. Do not edit by hand - re-run the script instead.
#
# nginx replaces \$remote_addr with CF-Connecting-IP only for requests that
# arrived FROM one of these addresses. A request from anywhere else keeps its
# own address no matter what headers it carries, which is what makes a forged
# CF-Connecting-IP useless.
"
while IFS= read -r cidr; do
  [ -z "$cidr" ] && continue
  nginx_body="${nginx_body}set_real_ip_from ${cidr};"$'\n'
done <<< "$ranges"
nginx_body="${nginx_body}
real_ip_header CF-Connecting-IP;
# Walk back through trusted addresses so a chain of Cloudflare hops resolves to
# the original client rather than to the last proxy.
real_ip_recursive on;
"

ufw_body="#!/usr/bin/env bash
$stamp_note
#   $V4_URL
#   $V6_URL
# Restricts 80/443 to Cloudflare, so the origin cannot be reached directly and
# the edge cannot be bypassed. Review it before running; it changes the
# firewall of whatever host it runs on.
#
# This does NOT open SSH. Make sure your SSH rule exists first, or you will
# lock yourself out:  sudo ufw allow from <your.ip> to any port 22 proto tcp
set -euo pipefail
[ \"\$(id -u)\" -eq 0 ] || { echo 'run with sudo' >&2; exit 1; }
ufw status | grep -q '22/tcp\\|OpenSSH' || {
  echo 'REFUSING: no SSH rule found in ufw - add one first or you will be locked out' >&2
  exit 1
}
# Drop any previous Cloudflare rules so repeated runs do not pile up.
ufw status numbered | grep -i 'cloudflare' | sed -E 's/^\\[ *([0-9]+).*/\\1/' | sort -rn | while read -r n; do
  ufw --force delete \"\$n\"
done
"
while IFS= read -r cidr; do
  [ -z "$cidr" ] && continue
  ufw_body="${ufw_body}ufw allow from ${cidr} to any port 80,443 proto tcp comment 'cloudflare'"$'\n'
done <<< "$ranges"
ufw_body="${ufw_body}echo 'Cloudflare ranges allowed on 80,443. Verify with: ufw status numbered'
"

if [ "$mode" = "check" ]; then
  fail=0
  for pair in "$NGINX_OUT:nginx" "$UFW_OUT:ufw"; do
    path="${pair%%:*}"; kind="${pair##*:}"
    [ "$kind" = "nginx" ] && want="$nginx_body" || want="$ufw_body"
    if [ ! -f "$path" ]; then
      echo "STALE: $path is missing"; fail=1; continue
    fi
    if ! printf '%s' "$want" | diff -q - "$path" >/dev/null 2>&1; then
      echo "STALE: $path differs from the published ranges"; fail=1
    else
      echo "ok: $path"
    fi
  done
  exit "$fail"
fi

printf '%s' "$nginx_body" > "$NGINX_OUT"
printf '%s' "$ufw_body" > "$UFW_OUT"
chmod +x "$UFW_OUT"
echo "Wrote $NGINX_OUT and $UFW_OUT ($count ranges)."
echo "Commit both, then redeploy so nginx picks them up."
